import 'dotenv/config';
import { randomUUID } from 'node:crypto';
import { afterAll, expect, it } from 'vitest';
import { getDatabase } from '@/lib/db';
import { persistObservation } from '@/ingestion/persist';
import { getEligiblePositions } from '@/server/positions';
import { NBA_POSITION_POLICY } from '@/positions/nba-policy';
import { fitsSlot } from '@/simulation/config';
import { openAcquisitionSlot } from '@/rosters/acquisition-slot';
const db = getDatabase(); afterAll(() => db.$disconnect());
it('uses the approved prospective NBA policy through shared draft/acquisition/roster eligibility with revisions and conflict quarantine', async () => {
  const provider = `nba-policy-${randomUUID()}`, player = await db.player.create({ data: { sport: 'NBA', displayName: `Synthetic NBA policy ${randomUUID()}`, isSynthetic: true } });
  await db.playerExternalId.create({ data: { sport: 'NBA', playerId: player.id, provider, externalId: 'athlete' } });
  await db.season.upsert({ where: { sport_startYear: { sport: 'NBA', startYear: 2041 } }, create: { sport: 'NBA', startYear: 2041, label: '2041–42' }, update: {} });
  const base = { provider, sport: 'NBA', entityKey: `nba-position:${provider}:athlete:2041`, revisionToken: '1', revisionOrdinal: 1, sourceReference: 'https://fixture.invalid/nba-position-policy', observedAt: '2041-11-02T12:00:00Z', effectiveAt: null, publishedAt: null, raw: { synthetic: true },
    normalized: { kind: 'NBA_POSITION_SNAPSHOT', player: { provider, externalId: 'athlete' }, seasonStartYear: 2041, sourcePosition: 'G', sourceRecordId: 'synthetic-row-1', sourceFingerprint: 'a'.repeat(64), sourceSnapshotDate: '2041-11-01', knownAt: '2041-11-01T12:00:00Z', validFrom: '2041-11-02T12:00:00Z', validUntil: null, precision: 'OBSERVED_SNAPSHOT', policyVersion: NBA_POSITION_POLICY, retracted: false } };
  const apply = (value: typeof base) => db.$transaction(tx => persistObservation(tx,value,new Date(value.observedAt)));
  const positions = (asOf: string) => getEligiblePositions({ playerId: player.id, sport: 'NBA', seasonYear: 2041, asOf: new Date(asOf) });
  expect((await apply(base)).outcome).toBe('ACCEPTED');
  expect((await apply(base)).outcome).toBe('DUPLICATE');
  expect((await positions('2041-11-02T11:59:59Z')).positions).toEqual([]);
  const eligible = await positions(base.observedAt);
  expect(eligible.positions).toEqual(['PG','SG']);
  expect(fitsSlot('NBA','PG',new Set(eligible.positions))).toBe(true);
  expect(fitsSlot('NBA','G',new Set(eligible.positions))).toBe(true);
  expect(fitsSlot('NBA','UTIL',new Set(eligible.positions))).toBe(true);
  expect(fitsSlot('NBA','PF',new Set(eligible.positions))).toBe(false);
  expect(openAcquisitionSlot({ sport: 'NBA', rosterId: 'synthetic', starters: ['PG','SG','G','SF','PF','F','C','C','UTIL'], bench: 0, universalBench: 0, positions: new Set(eligible.positions), entries: [] })).toEqual({ slot: 'PG', slotIndex: 1 });
  const specific = { ...base, revisionToken: '2', revisionOrdinal: 2, normalized: { ...base.normalized, sourcePosition: 'PG' } };
  expect((await apply(specific)).outcome).toBe('ACCEPTED');
  expect((await positions(base.observedAt)).positions).toEqual(['PG']);
  const conflictingRevision = { ...specific, observedAt: '2041-11-02T13:00:00Z', normalized: { ...specific.normalized, sourcePosition: 'SG' } };
  const conflictReceipt = await apply(conflictingRevision);
  expect(conflictReceipt.outcome, conflictReceipt.reason).toBe('QUARANTINED');
  expect(conflictReceipt.targets).toMatchObject({ playerId: player.id, nbaPositionConflict: true });
  expect((await positions(base.observedAt)).positions).toEqual(['PG']);
  expect((await positions(conflictingRevision.observedAt)).positions).toEqual([]);
  const unknownActor = { ...conflictingRevision, normalized: { ...conflictingRevision.normalized, player: { provider, externalId: 'unknown-actor' } } };
  const unknownReceipt = await apply(unknownActor);
  expect(unknownReceipt.outcome).toBe('QUARANTINED');
  expect(unknownReceipt.targets).not.toHaveProperty('playerId');
  const newer = { ...base, revisionToken: '3', revisionOrdinal: 3, observedAt: '2041-11-03T12:00:00Z', normalized: { ...base.normalized, sourcePosition: 'F-C', validFrom: '2041-11-03T12:00:00Z' } };
  expect((await apply(newer)).outcome).toBe('ACCEPTED');
  expect((await positions(newer.observedAt)).positions).toEqual(['C','PF','SF']);
  expect((await positions(base.observedAt)).positions).toEqual(['PG']);
  const conflict = { ...newer, provider: `${provider}-conflict`, revisionToken: '1', revisionOrdinal: 1, normalized: { ...newer.normalized, sourcePosition: 'SG' } };
  expect((await apply(conflict)).outcome).toBe('QUARANTINED');
  expect((await positions(newer.observedAt)).positions).toEqual([]);
  const retract = { ...newer, revisionToken: '4', revisionOrdinal: 4, observedAt: '2041-11-04T12:00:00Z', normalized: { ...newer.normalized, retracted: true, validFrom: '2041-11-04T12:00:00Z' } };
  expect((await apply(retract)).outcome).toBe('ACCEPTED');
  expect((await positions(retract.observedAt))).toMatchObject({ available: true, positions: [] });
  expect(await db.playerPositionEvidence.count({ where: { playerId: player.id } })).toBe(0);
  const observations = await db.professionalDataObservation.findMany({ where: { sport: 'NBA', category: 'NBA_POSITION_SNAPSHOT', decisions: { some: { targets: { path: ['playerId'], equals: player.id } } } } });
  expect(observations.every(row => row.effectiveAt === null && row.publishedAt === null)).toBe(true);
});
